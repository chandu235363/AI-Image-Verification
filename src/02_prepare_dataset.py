from __future__ import annotations

import csv
import random
import shutil
from pathlib import Path

from PIL import Image

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROCESSED_DIR = PROJECT_ROOT / "data/processed"
MANIFEST_PATH = PROCESSED_DIR / "dataset_manifest.csv"
IMAGE_SIZE = (224, 224)
MAX_IMAGES_PER_CLASS = 2000
SEED = 42
VALID_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff"}

DATASET_SOURCES = {
    "Real": {"label": 0, "path": PROJECT_ROOT / "data/raw/coco/val2017"},
    "AI-Generated": {"label": 1, "path": PROJECT_ROOT / "data/raw/genimage/ai"},
    "Manipulated": {"label": 2, "path": PROJECT_ROOT / "data/raw/casia/Tp"},
}


def is_readable_image(image_path: Path) -> bool:
    """Return True only when PIL can open and verify the image."""
    try:
        with Image.open(image_path) as image:
            image.verify()
        return True
    except Exception:
        return False


def collect_readable_images(source_dir: Path) -> list[Path]:
    """Recursively collect readable image files from one raw source."""
    if not source_dir.is_dir():
        return []

    return sorted(
        path.resolve()
        for path in source_dir.rglob("*")
        if path.is_file()
        and path.suffix.lower() in VALID_EXTENSIONS
        and is_readable_image(path)
    )


def split_images(image_paths: list[Path]) -> dict[str, list[Path]]:
    """Create deterministic, non-overlapping 70/15/15 splits."""
    shuffled = list(image_paths)
    random.Random(SEED).shuffle(shuffled)
    total = len(shuffled)
    validation_count = max(1, round(total * 0.15))
    test_count = max(1, round(total * 0.15))
    train_end = total - validation_count - test_count
    validation_end = train_end + validation_count
    return {
        "train": shuffled[:train_end],
        "val": shuffled[train_end:validation_end],
        "test": shuffled[validation_end:],
    }


def clear_prepared_outputs() -> None:
    """Clear only files previously generated by this preparation script."""
    for split in ("train", "val", "test"):
        split_dir = PROCESSED_DIR / split
        if split_dir.exists():
            shutil.rmtree(split_dir)
    if MANIFEST_PATH.exists():
        MANIFEST_PATH.unlink()


def prepare_image(source_path: Path, destination_path: Path) -> bool:
    """Resize and save a prepared JPEG, then verify the saved copy."""
    try:
        with Image.open(source_path) as image:
            prepared = image.convert("RGB").resize(IMAGE_SIZE, Image.Resampling.LANCZOS)
            prepared.save(destination_path, format="JPEG", quality=95)
        with Image.open(destination_path) as saved_image:
            saved_image.verify()
        with Image.open(destination_path) as saved_image:
            return saved_image.size == IMAGE_SIZE
    except Exception:
        if destination_path.exists():
            destination_path.unlink()
        return False


def write_manifest(rows: list[dict[str, object]]) -> None:
    """Write the prepared dataset CSV."""
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    with MANIFEST_PATH.open("w", newline="", encoding="utf-8") as manifest_file:
        writer = csv.DictWriter(
            manifest_file,
            fieldnames=["filepath", "label", "class_name", "split"],
        )
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    print("Preparing balanced 3-class dataset at 224x224.")
    print(f"Output directory: {PROCESSED_DIR.resolve()}")
    print("Raw images will not be modified.")
    print("=" * 80)

    readable_by_class: dict[str, list[Path]] = {}
    for class_name, source in DATASET_SOURCES.items():
        images = collect_readable_images(source["path"])
        readable_by_class[class_name] = images
        print(f"{class_name}: {len(images)} readable source images")
        print(f"Source: {source['path']}")

    missing_classes = [
        class_name
        for class_name, images in readable_by_class.items()
        if len(images) < MAX_IMAGES_PER_CLASS
    ]
    if missing_classes:
        raise RuntimeError(
            "Each class must have at least 2,000 readable images. "
            f"Insufficient classes: {', '.join(missing_classes)}"
        )

    clear_prepared_outputs()
    rows: list[dict[str, object]] = []
    selected_paths: set[Path] = set()
    statistics: dict[str, dict[str, int]] = {}

    for class_name, source in DATASET_SOURCES.items():
        selected = readable_by_class[class_name][:MAX_IMAGES_PER_CLASS]
        split_items = split_images(selected)
        class_statistics = {split: 0 for split in ("train", "val", "test")}

        for split_name, source_paths in split_items.items():
            output_dir = PROCESSED_DIR / split_name / class_name
            output_dir.mkdir(parents=True, exist_ok=True)
            for index, source_path in enumerate(source_paths, start=1):
                if source_path in selected_paths:
                    raise RuntimeError(f"Duplicate source path assigned to multiple splits: {source_path}")
                selected_paths.add(source_path)

                output_path = output_dir / f"{class_name.lower().replace('-', '_')}_{index:05d}.jpg"
                if not prepare_image(source_path, output_path):
                    raise RuntimeError(f"Could not prepare image: {source_path}")

                rows.append({
                    "filepath": str(output_path.resolve()),
                    "label": source["label"],
                    "class_name": class_name,
                    "split": split_name,
                })
                class_statistics[split_name] += 1

        statistics[class_name] = class_statistics

    if len(selected_paths) != MAX_IMAGES_PER_CLASS * len(DATASET_SOURCES):
        raise RuntimeError("Prepared image paths are not unique or the expected count was not created.")

    write_manifest(rows)

    print("\nFinal dataset statistics")
    print("=" * 80)
    for class_name, class_statistics in statistics.items():
        total = sum(class_statistics.values())
        print(
            f"{class_name} (label {DATASET_SOURCES[class_name]['label']}): "
            f"total={total}, train={class_statistics['train']}, "
            f"val={class_statistics['val']}, test={class_statistics['test']}"
        )
    print(f"Total prepared images: {len(rows)}")
    print(f"Manifest: {MANIFEST_PATH.resolve()}")
    print("All prepared images were opened and verified at 224x224.")
    print("Training was not started.")


if __name__ == "__main__":
    main()
